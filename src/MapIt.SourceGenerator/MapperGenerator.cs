using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace MapIt.SourceGenerator
{
    /// <summary>
    /// A compile-time mapper generator (reflection-free, trimming/AOT-friendly). Decorate a
    /// partial class with <c>[Mapper]</c> and declare partial mapping methods such as
    /// <c>public partial TDest ToDto(TSource src);</c>. The generator emits a body that assigns
    /// each settable destination property from the same-named source property; when another
    /// mapping method in the same class maps a nested member's pair, that method is called.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class MapperGenerator : IIncrementalGenerator
    {
        private const string MapperAttributeName = "MapIt.Generated.MapperAttribute";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            // Emit the marker attribute.
            context.RegisterPostInitializationOutput(ctx => ctx.AddSource("MapperAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8)));

            var classes = context.SyntaxProvider.CreateSyntaxProvider(
                predicate: static (node, _) => node is ClassDeclarationSyntax c && c.AttributeLists.Count > 0,
                transform: static (ctx, _) => GetMapperClass(ctx))
                .Where(static c => c is not null);

            context.RegisterSourceOutput(classes, static (spc, cls) => Emit(spc, cls!));
        }

        private static MapperClassInfo? GetMapperClass(GeneratorSyntaxContext ctx)
        {
            var classDecl = (ClassDeclarationSyntax)ctx.Node;
            var symbol = ctx.SemanticModel.GetDeclaredSymbol(classDecl) as INamedTypeSymbol;
            if (symbol == null) return null;
            if (!symbol.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == MapperAttributeName)) return null;

            var methods = new List<MapMethodInfo>();
            foreach (var member in symbol.GetMembers().OfType<IMethodSymbol>())
            {
                if (!member.IsPartialDefinition) continue;
                if (member.Parameters.Length != 1) continue;
                if (member.ReturnsVoid) continue;
                methods.Add(new MapMethodInfo(member.Name, member.DeclaredAccessibility, member.Parameters[0], member.ReturnType, member.IsStatic));
            }
            if (methods.Count == 0) return null;

            return new MapperClassInfo(symbol, methods);
        }

        private static void Emit(SourceProductionContext spc, MapperClassInfo cls)
        {
            var symbol = cls.Symbol;
            var ns = symbol.ContainingNamespace.IsGlobalNamespace ? null : symbol.ContainingNamespace.ToDisplayString();
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            if (ns != null) { sb.AppendLine($"namespace {ns}"); sb.AppendLine("{"); }
            sb.AppendLine($"    partial class {symbol.Name}");
            sb.AppendLine("    {");

            foreach (var m in cls.Methods)
            {
                var srcType = m.Parameter.Type;
                var destType = (ITypeSymbol)m.ReturnType;
                var acc = AccessibilityKeyword(m.DeclaredAccessibility);
                var stat = m.IsStatic ? "static " : "";
                var p = m.Parameter.Name;

                sb.AppendLine($"        {acc} {stat}partial {destType.ToDisplayString()} {m.Name}({srcType.ToDisplayString()} {p})");
                sb.AppendLine("        {");
                sb.AppendLine($"            if ({p} is null) return default!;");
                sb.AppendLine($"            var dest = new {destType.ToDisplayString()}();");
                EmitAssignments(sb, srcType, destType, p, "dest", cls);
                sb.AppendLine("            return dest;");
                sb.AppendLine("        }");
                sb.AppendLine();
            }

            sb.AppendLine("    }");
            if (ns != null) sb.AppendLine("}");

            spc.AddSource($"{symbol.Name}.Mapper.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        private static void EmitAssignments(StringBuilder sb, ITypeSymbol srcType, ITypeSymbol destType, string srcVar, string destVar, MapperClassInfo cls)
        {
            var srcProps = GetReadableProperties(srcType);
            foreach (var destProp in GetWritableProperties(destType))
            {
                if (!srcProps.TryGetValue(destProp.Name.ToLowerInvariant(), out var srcProp)) continue;

                var sameType = SymbolEqualityComparer.Default.Equals(srcProp.Type, destProp.Type);
                if (sameType)
                {
                    sb.AppendLine($"            {destVar}.{destProp.Name} = {srcVar}.{srcProp.Name};");
                    continue;
                }

                // Nested: is there a mapping method in this class for (srcProp.Type -> destProp.Type)?
                var nested = cls.Methods.FirstOrDefault(mm =>
                    SymbolEqualityComparer.Default.Equals(mm.Parameter.Type, srcProp.Type) &&
                    SymbolEqualityComparer.Default.Equals(mm.ReturnType, destProp.Type));
                if (nested != null)
                {
                    sb.AppendLine($"            {destVar}.{destProp.Name} = {nested.Name}({srcVar}.{srcProp.Name});");
                    continue;
                }

                // Implicit numeric/convertible assignment attempt via cast (best effort).
                if (IsImplicitlyConvertible(srcProp.Type, destProp.Type))
                    sb.AppendLine($"            {destVar}.{destProp.Name} = ({destProp.Type.ToDisplayString()}){srcVar}.{srcProp.Name};");
            }
        }

        private static bool IsImplicitlyConvertible(ITypeSymbol from, ITypeSymbol to)
        {
            // Allow numeric widening-ish assignments; keep conservative.
            var numeric = new[] { "byte", "sbyte", "short", "ushort", "int", "uint", "long", "ulong", "float", "double", "decimal" };
            return numeric.Contains(from.ToDisplayString()) && numeric.Contains(to.ToDisplayString());
        }

        private static Dictionary<string, IPropertySymbol> GetReadableProperties(ITypeSymbol type)
        {
            var dict = new Dictionary<string, IPropertySymbol>();
            foreach (var t in Bases(type))
                foreach (var p in t.GetMembers().OfType<IPropertySymbol>())
                    if (!p.IsStatic && p.GetMethod != null && p.DeclaredAccessibility == Accessibility.Public)
                        dict[p.Name.ToLowerInvariant()] = p;
            return dict;
        }

        private static IEnumerable<IPropertySymbol> GetWritableProperties(ITypeSymbol type)
        {
            var seen = new HashSet<string>();
            foreach (var t in Bases(type))
                foreach (var p in t.GetMembers().OfType<IPropertySymbol>())
                    if (!p.IsStatic && p.SetMethod != null && p.SetMethod.DeclaredAccessibility == Accessibility.Public && seen.Add(p.Name))
                        yield return p;
        }

        private static IEnumerable<ITypeSymbol> Bases(ITypeSymbol type)
        {
            for (var t = type; t != null && t.SpecialType != SpecialType.System_Object; t = t.BaseType)
                yield return t;
        }

        private static string AccessibilityKeyword(Accessibility a) => a switch
        {
            Accessibility.Public => "public",
            Accessibility.Internal => "internal",
            Accessibility.Protected => "protected",
            Accessibility.Private => "private",
            _ => "public",
        };

        private const string AttributeSource = @"// <auto-generated/>
#nullable enable
namespace MapIt.Generated
{
    /// <summary>Marks a partial class whose partial mapping methods are implemented by the MapIt source generator.</summary>
    [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false)]
    internal sealed class MapperAttribute : global::System.Attribute
    {
    }
}
";

        private sealed class MapperClassInfo
        {
            public MapperClassInfo(INamedTypeSymbol symbol, List<MapMethodInfo> methods) { Symbol = symbol; Methods = methods; }
            public INamedTypeSymbol Symbol { get; }
            public List<MapMethodInfo> Methods { get; }
        }

        private sealed class MapMethodInfo
        {
            public MapMethodInfo(string name, Accessibility acc, IParameterSymbol parameter, ITypeSymbol returnType, bool isStatic)
            {
                Name = name; DeclaredAccessibility = acc; Parameter = parameter; ReturnType = returnType; IsStatic = isStatic;
            }
            public string Name { get; }
            public Accessibility DeclaredAccessibility { get; }
            public IParameterSymbol Parameter { get; }
            public ITypeSymbol ReturnType { get; }
            public bool IsStatic { get; }
        }
    }
}
